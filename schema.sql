CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, name VARCHAR(80) NOT NULL, email VARCHAR(190) UNIQUE NOT NULL,
 password_hash VARCHAR(100) NOT NULL, coins BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ledger (
 id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, amount BIGINT NOT NULL,
 kind VARCHAR(40) NOT NULL, reference VARCHAR(100) UNIQUE NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS rewards (
 id VARCHAR(40) PRIMARY KEY, title VARCHAR(100) NOT NULL, cost INT UNSIGNED NOT NULL,
 external BOOLEAN NOT NULL DEFAULT FALSE, active BOOLEAN NOT NULL DEFAULT TRUE
);
