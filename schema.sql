CREATE TABLE IF NOT EXISTS redemptions (
 id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, reward_id VARCHAR(40) NOT NULL,
 game_id VARCHAR(80), cost INT UNSIGNED NOT NULL,
 status ENUM('pending','completed','rejected') NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (reward_id) REFERENCES rewards(id)
);
CREATE TABLE IF NOT EXISTS demo_sessions (
 id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, consumed BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
